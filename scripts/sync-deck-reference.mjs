/** Import reference artwork/materials without writing to the reference checkout.
 * Usage: node scripts/sync-deck-reference.mjs /absolute/path/to/deluge-deck
 * Geometry and native controls remain in deck-reference-adapter.less.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import postcss from 'postcss';
import { execFileSync } from 'node:child_process';
const source = path.resolve(process.argv[2] || '.dream-loop/deck-latest');
const git = args => execFileSync('git', ['-C', source, ...args], { encoding: 'utf8' }).trim();
const revision = git(['rev-parse','--short','HEAD']);
const dirty = git(['status','--porcelain','--','src/assets','src/app','src/themes']);
const version = JSON.parse(fs.readFileSync(path.join(source,'package.json'),'utf8')).version;
const provenance = `${version} · ${revision}${dirty ? ' + local theme changes' : ''}`;
const target = 'src/renderer/styles/app/partials/deck-reference.less';
const existingOutput = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
const darkhandBlock = existingOutput.match(/\/\* darkhand\.css \*\/[\s\S]*?(?=\n\/\* [\w-]+\.css \*\/|$)/)?.[0] || '';
const files = ['valentine','halloween','christmas','new-year','independence','core','signatures','matrix','independence-reference','sports-expansion','sports','darkhand','mets','sports-bespoke','yankees','sports-heritage'];
if (fs.existsSync(path.join(source, 'src/themes/core-refined.css'))) files.push('core-refined');
if (fs.existsSync(path.join(source, 'src/themes/forest.css'))) files.push('forest');
if (files.includes('core-refined')) {
  const palettePath = 'src/renderer/styles/deck-palettes.less';
  const palettes = fs.readFileSync(palettePath, 'utf8').replace(/(:root\[data-theme="(?:dark|light|ocean|forest|sunset)"\]):not\(#dream-loop-skip\)/g, '$1');
  fs.writeFileSync(palettePath, palettes);
}
for (const theme of ['paper-folio', 'ocean-expedition', 'sunset-horizon', 'midnight-observatory']) {
  if (fs.existsSync(path.join(source, 'src/themes', `${theme}.css`))) files.push(theme);
}
const classes = {
  'app-shell':'main.wrapper', 'main-content':'main-panel', workspace:'deck-overview',
  'table-shell':'main-content', topbar:'deck-control-strip', 'topbar-heading':'deck-overview-heading',
  'stats-grid':'deck-stats-grid', 'stat-card':'deck-stat-card', 'stat-icon':'deck-stat-icon',
  'stat-spark':'deck-stat-chart', sidebar:'torrent.sidebar', 'add-button':'deck-sidebar-add',
  'nav-label':'deck-sidebar-caption', 'nav-item':'nav-item', 'sidebar-bottom':'torrent-sidebar-footer',
  'sidebar-toggle':'torrent-sidebar-toggle', 'search-wrap':'ui.fluid.search',
  'progress-wrap':'deck-progress', 'progress-track':'deck-progress-track', 'progress-bar':'bar',
  'independence-flag':'deck-progress-flag',
  'deck-status-rail':'status-bar', 'torrent-name':'torrent-name-content',
  'modal-card':'ui.modal', 'detail-drawer':'torrent-details-panel', 'drawer-tabs':'torrent-details-tabs',
  'context-menu':'ui.context.menu', 'column-resize-handle':'rz-handle',
};
let output = `/* Deluge Deck ${provenance}. Generated by scripts/sync-deck-reference.mjs.\n   Original theme credits are retained below. Native layout adapters are separate. */\n`;
for (const name of files) {
  // Keep Darkhand's existing imported CSS byte-for-byte. Its maintenance stays
  // independent from reference theme refreshes.
  if (name === 'darkhand') {
    if (darkhandBlock) output += '\n' + darkhandBlock + '\n';
    continue;
  }
  const css = postcss.parse(fs.readFileSync(path.join(source,'src/themes',name+'.css'),'utf8'));
  css.walkRules(rule => {
    if (rule.parent.type === 'atrule' && rule.parent.name.endsWith('keyframes')) return;
    // Desktop owns the shell layout. Web breakpoints can move or flatten these containers.
    const redesigned = ['paper-folio', 'ocean-expedition', 'sunset-horizon', 'midnight-observatory'].includes(name);
    if (redesigned && /body \.(app-shell|main-content|workspace)$/.test(rule.selector)) {
      for (const declaration of [...rule.nodes]) {
        if (/^(display|grid-|column-gap|align-|padding|margin|width|height|min-|max-|position|overflow|flex|inset)/.test(declaration.prop || '')) declaration.remove();
      }
      if (!rule.nodes.length) { rule.remove(); return; }
    }
    // Terminal already has its own faithful CRT implementation. Shared reference
    // materials are scoped away from it, including generic sports/gallery rules.
    rule.selector = rule.selector.replace(/:root/g, 'html[data-theme]:not([data-theme="terminal"])')
      .replace(/\.([\w-]+)/g, (match,key) => classes[key] ? '.'+classes[key] : match)
      .replace(/tr\.selected/g,'tr.active');
    rule.selector = postcss.list.comma(rule.selector).map(selector => selector.startsWith('html') ? selector : 'html[data-theme]:not([data-theme="terminal"]) '+selector).join(', ');
    // Darkhand's React shell geometry is replaced by the native panel adapter.
    if (name === 'darkhand' && /\.(main\.wrapper|main-panel|deck-overview|torrent\.sidebar)(?![\w-])/.test(rule.selector) && !rule.selector.includes('::')) {
      for (const decl of [...rule.nodes]) {
        if (decl.type === 'decl' && /^(position|inset|left|right|top|bottom|width|height|min-height|padding|margin.*|gap|display|flex.*|order|overflow)$/.test(decl.prop)) decl.remove();
      }
    }
    // Percentage layout is a deliberate Electorrent preference: beneath the meter.
    if (name === 'darkhand' && rule.selector.includes('.deck-progress>span')) rule.remove();
    // Special SVG progress artwork is already ported with live fill/clipping.
    if (['halloween','christmas','independence'].includes(name) && /\.(deck-progress|bar|potion|candy)/.test(rule.selector)) rule.remove();
  });
  css.walkDecls(decl => {
    decl.value = decl.value.replace(/\.\.\/assets\//g,'../../assets/deck/').replace(/\?inline/g,'');
    // Less evaluates arithmetic. Preserve a CSS position / size separator after calc().
    if (decl.prop === 'background') decl.value = decl.value.replace(/\)\s*\/\s*(?=(?:\d|calc\())/g, ') ~"/" ');
    if (/^grid-(row|column|area)$/.test(decl.prop) && decl.value.includes('/')) {
      decl.value = `~"${decl.value}"`;
    }
  });
  output += '\n/* '+name+'.css */\n'+css.toString()+'\n';
}
fs.writeFileSync(target, output.trimEnd()+'\n');
fs.cpSync(path.join(source,'src/assets'),'src/renderer/assets/deck',{recursive:true,filter:assetPath => !/theme-previews\/(?:darkhand|terminal)-optimized\.webp$/.test(assetPath)});
const { SPORTS_DESIGNS } = await import(pathToFileURL(path.join(source,'src/app/sports-designs.js')));
const { SPORTS_CLUBS } = await import(pathToFileURL(path.join(source,'src/app/sports-clubs.js')));
const metadataPath = 'src/shared/deck-themes.ts';
let metadata = fs.readFileSync(metadataPath,'utf8').replace(/\nexport const DECK_SPORTS_DESIGNS[\s\S]*$/,'');
metadata = metadata.replace(/^\/\/ Synced from micro23\/deluge-deck[^\n]*/, `// Synced from micro23/deluge-deck ${provenance}.`);
metadata = metadata.replace(/export const DECK_SPORTS_CLUBS = [\s\S]*$/, 'export const DECK_SPORTS_CLUBS = '+JSON.stringify(SPORTS_CLUBS,null,4)+';\n');
metadata = metadata.replace('"independence": "Independence"', '"independence": "USA"');
metadata += '\nexport const DECK_SPORTS_DESIGNS = '+JSON.stringify(SPORTS_DESIGNS,null,4)+';\n';
metadata += '\nexport const DECK_CORE_THEMES = '+JSON.stringify({dark:'Midnight',light:'Paper',ocean:'Ocean',forest:'Forest',sunset:'Sunset'},null,4)+';\n';
fs.writeFileSync(metadataPath,metadata);
console.log('Imported '+(files.length-1)+' Deck theme materials and local assets.');
